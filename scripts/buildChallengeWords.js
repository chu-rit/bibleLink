const byId = new Map(lib.map((w) => [w.id, w]));
const byWord = new Map();
lib.forEach((w) => { if (!byWord.has(w.word)) byWord.set(w.word, w); });

const out = [];
const missed = [];
for (const [key, category] of PICKS) {
  const src = byId.get(key) || byWord.get(key);
  if (!src) { missed.push(key); continue; }
  if (DROPS.has(src.word)) continue;
  const len = jamoLength(src.word);
  if (len < 7 || len > 10) { missed.push(`${key}(${len}자모)`); continue; }
  const firstRef = (src.references || [])[0] || '';
  let book = firstRef.replace(/[\d:,\-–;장절편\s].*$/, '').trim();
  if (['마태', '마가', '누가', '요한'].includes(book)) book += '복음';
  const hint2 = book && book === src.word ? '자기 이름을 딴 책에 등장' : `${book}에 등장`;
  out.push({
    id: src.id,
    name: src.word,
    difficulty: src.difficulty,
    hint1: category,
    hint2,
    hint3: HINT3[src.id] || src.definition,
  });
}

